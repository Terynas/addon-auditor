"""Run luacheck and parse its plain output into structured records.

If the addon (or a parent dir) has ``.luacheckrc`` it is used. Otherwise a config is generated:
``std = "lua51"``, every known API global for the addon's profiles as ``read_globals``, and the
addon's legitimate globals (SavedVariables, ``SLASH_*``, addon-prefixed names) as ``globals``.
"""

from __future__ import annotations

import os
import re
import shutil
import subprocess
import tempfile
from dataclasses import dataclass
from pathlib import Path

from ..core.builtins import ALWAYS_KNOWN
from .api_index import load_profile

_LINE = re.compile(r"^(?P<file>.+?):(?P<line>\d+):(?P<col>\d+)(?:-(?P<end>\d+))?: \((?P<code>[EW]\d{3})\) (?P<msg>.*)$")


@dataclass
class LuacheckIssue:
    file: str  # relative to addon root
    line: int
    col: int
    end_col: int | None
    code: str
    message: str


@dataclass
class LuacheckResult:
    available: bool
    binary: str | None
    config: str | None  # path used or "generated"
    issues: list[LuacheckIssue]
    error: str | None = None


def find_luacheck(start: Path | None = None) -> str | None:
    env = os.environ.get("ADDON_AUDITOR_LUACHECK") or os.environ.get("WOW_LUACHECK")
    if env and Path(env).is_file():
        return env
    cands: list[Path] = []
    if start is not None:
        for d in [start, *start.parents]:
            cands += [d / ".tools/luacheck/bin/luacheck", d / ".tools/lua51/bin/luacheck"]
    cands += [Path.home() / ".luarocks/bin/luacheck"]
    for c in cands:
        if c.is_file() and os.access(c, os.X_OK):
            return str(c)
    return shutil.which("luacheck")


def find_config(root: Path) -> Path | None:
    """Nearest ``.luacheckrc`` at or above ``root``, not crossing the enclosing git repository root."""
    explicit = os.environ.get("ADDON_AUDITOR_LUACHECKRC")
    if explicit and Path(explicit).is_file():
        return Path(explicit)
    for d in [root, *root.parents]:
        p = d / ".luacheckrc"
        if p.is_file():
            return p
        if (d / ".git").exists():
            return None
    return None


def _lua_list(names: list[str]) -> str:
    return "{\n" + "".join(f'  "{n}",\n' for n in sorted(set(names))) + "}"


# Client tables addons are expected to add fields to.
WRITABLE_CLIENT_GLOBALS = ("SlashCmdList", "StaticPopupDialogs", "UISpecialFrames", "UIPanelWindows",
                           "BINDING_HEADER_OTHER")


def generate_config(profiles: set[str], addon_globals: list[str]) -> str:
    read_globals: set[str] = set(ALWAYS_KNOWN)
    for p in profiles:
        api = load_profile(p)
        if api is not None:
            read_globals |= api.globals
    addon_globals = list(addon_globals) + list(WRITABLE_CLIENT_GLOBALS)
    read_globals -= set(addon_globals)
    return (
        "-- generated by addon-auditor\n"
        'std = "lua51"\n'
        "max_line_length = false\n"
        "codes = true\n"
        'ignore = { "212", "213" }\n'
        f"globals = {_lua_list(addon_globals)}\n"
        f"read_globals = {_lua_list(sorted(read_globals))}\n"
    )


def addon_template(addon: str, profiles: set[str], writes: list[str], reads: list[str]) -> str:
    """Compact, commit-friendly ``.luacheckrc`` listing only what this addon writes and reads."""
    return (
        f"-- .luacheckrc for {addon} (generated by `addon-auditor luacheckrc`; edit freely)\n"
        f"-- clients: {', '.join(sorted(profiles))}\n"
        'std = "lua51"\n'
        "max_line_length = false\n"
        "codes = true\n"
        'exclude_files = { "Libs/", "libs/", ".release/", "tests/", "spec/" }\n'
        "-- 212/213: unused arguments / loop variables are normal in event handlers\n"
        'ignore = { "212", "213" }\n\n'
        "-- globals this addon defines\n"
        f"globals = {_lua_list(list(writes) + list(WRITABLE_CLIENT_GLOBALS))}\n\n"
        "-- client API this addon reads (re-run the command after using new APIs)\n"
        f"read_globals = {_lua_list(reads)}\n"
    )


def run(root: Path, files: list[str], profiles: set[str], addon_globals: list[str],
        timeout: int = 120) -> LuacheckResult:
    binary = find_luacheck(root)
    if binary is None:
        return LuacheckResult(False, None, None, [], "luacheck not found (install via LuaRocks or set ADDON_AUDITOR_LUACHECK)")
    if not files:
        return LuacheckResult(True, binary, None, [])
    cfg_path = find_config(root)
    tmp: str | None = None
    if cfg_path is None:
        fd, tmp = tempfile.mkstemp(suffix=".luacheckrc", prefix="addon-auditor-")
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            fh.write(generate_config(profiles, addon_globals))
        cfg_used = tmp
        cwd = root
    else:
        cfg_used = str(cfg_path)
        cwd = cfg_path.parent
    abs_files = [str((root / f).resolve()) for f in files]
    cmd = [binary, "--formatter", "plain", "--codes", "--ranges", "--no-color", "--no-cache",
           "--config", cfg_used, *abs_files]
    try:
        proc = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, timeout=timeout)
    except (OSError, subprocess.TimeoutExpired) as e:
        return LuacheckResult(False, binary, cfg_used, [], str(e))
    finally:
        if tmp:
            os.unlink(tmp)
    issues: list[LuacheckIssue] = []
    root_res = root.resolve()
    for line in proc.stdout.splitlines():
        m = _LINE.match(line.strip())
        if not m:
            continue
        p = Path(m.group("file"))
        if not p.is_absolute():
            p = (cwd / p).resolve()
        try:
            rel = p.resolve().relative_to(root_res).as_posix()
        except ValueError:
            rel = p.as_posix()
        issues.append(LuacheckIssue(rel, int(m.group("line")), int(m.group("col")),
                                    int(m.group("end")) if m.group("end") else None,
                                    m.group("code"), m.group("msg")))
    err = None
    if proc.returncode >= 3 and not issues:
        err = (proc.stderr or proc.stdout).strip()[-2000:]
    return LuacheckResult(True, binary, "generated" if tmp else cfg_used, issues, err)
